#!/usr/bin/env python3
"""Generate the launcher icon from the iOS app's icon layers.

The iOS app's icon (meteocool/ios, meteocool/AppIcon.icon, written by its
scripts/app-icon.py) is the cloud logo with a navy outline and rain, on white,
or white lines on near-black when dark. Its layers are SVGs on a 1024 grid;
this script turns them into:

  res/drawable/ic_launcher_foreground.xml        cloud, outline, rain (light)
  res/drawable-night/ic_launcher_foreground.xml  the same with the dark lines
  res/drawable/ic_launcher_monochrome.xml        outline and rain, for themed icons
  res/values(-night)/ic_launcher_background.xml  white, near-black
  res/mipmap-*/ic_launcher(_round).png           Android 7.1 and older
  metadata/en-US/images/icon.png                 the store icon, 512 px

Usage:
    python3 scripts/app-icon.py [path/to/ios]

The iOS checkout defaults to $MC_IOS, then ../ios next to this repository.
Needs rsvg-convert (Homebrew: librsvg) for the PNGs.
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app" / "src" / "main" / "res"

WHITE = "#FFFFFF"
NEAR_BLACK = "#101822"  # the iOS icon's dark fill, srgb 0.063, 0.094, 0.133

# The adaptive icon shows the middle 72 of its 108 dp, and only the middle 66
# for sure; the logo is scaled into that circle. Legacy icons show it all.
ADAPTIVE_SCALE = 0.6
LEGACY_SCALE = 0.92

LEGACY_SIZES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def ios_path() -> Path:
    if len(sys.argv) > 1:
        return Path(sys.argv[1])
    if os.environ.get("MC_IOS"):
        return Path(os.environ["MC_IOS"])
    return ROOT.parent / "ios"


def layer(assets: Path, name: str) -> tuple[str, list[dict[str, str]]]:
    """The layer's group transform and its paths with their style."""
    svg = (assets / f"{name}.svg").read_text()
    transform = re.search(r'<g transform="([^"]*)"', svg).group(1)
    paths = []
    for d, style in re.findall(r'<path d="([^"]*)" style="([^"]*)"', svg):
        props = dict(item.split(":", 1) for item in style.strip(";").split(";"))
        paths.append({"d": d, **props})
    return transform, paths


def colour(value: str) -> str:
    if value == "white":
        return WHITE
    r, g, b = (int(v) for v in re.match(r"rgb\((\d+),(\d+),(\d+)\)", value).groups())
    return f"#{r:02X}{g:02X}{b:02X}"


def vector(layers: list[tuple[str, list[dict[str, str]]]], monochrome: bool = False) -> str:
    """A 108 dp VectorDrawable of the layers, back to front, scaled into the safe zone."""
    tx, ty, s = (float(v) for v in re.findall(r"[\d.]+", layers[0][0]))
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by scripts/app-icon.py from the iOS app's icon layers. Do not edit. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '        android:width="108dp"',
        '        android:height="108dp"',
        '        android:viewportWidth="1024"',
        '        android:viewportHeight="1024">',
        f'    <group android:pivotX="512" android:pivotY="512" android:scaleX="{ADAPTIVE_SCALE}" android:scaleY="{ADAPTIVE_SCALE}">',
        f'        <group android:translateX="{tx}" android:translateY="{ty}" android:scaleX="{s}" android:scaleY="{s}">',
    ]
    for _, paths in layers:
        for p in paths:
            fill = "#FFFFFFFF" if monochrome else colour(p["fill"])
            attrs = [f'android:pathData="{p["d"]}"', f'android:fillColor="{fill}"']
            if "stroke" in p:
                attrs += [
                    f'android:strokeColor="{"#FFFFFFFF" if monochrome else colour(p["stroke"])}"',
                    f'android:strokeWidth="{p["stroke-width"]}"',
                    f'android:strokeLineJoin="{p.get("stroke-linejoin", "miter")}"',
                ]
            lines.append("            <path " + "\n                  ".join(attrs) + " />")
    lines += ["        </group>", "    </group>", "</vector>", ""]
    return "\n".join(lines)


def background(value: str) -> str:
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by scripts/app-icon.py. Do not edit. -->\n"
        "<resources>\n"
        f'    <color name="ic_launcher_background">{value}</color>\n'
        "</resources>\n"
    )


def flat_svg(assets: Path, shape: str) -> str:
    """The light icon as one SVG: white square, rounded square or circle, logo on top."""
    body = "".join(
        re.search(r"<svg[^>]*>(.*)</svg>", (assets / f"{name}.svg").read_text(), re.S).group(1)
        for name in ("cloud", "outline", "rain")
    )
    plate = {
        "square": f'<rect width="1024" height="1024" fill="{WHITE}"/>',
        "rounded": f'<rect x="32" y="32" width="960" height="960" rx="180" fill="{WHITE}"/>',
        "circle": f'<circle cx="512" cy="512" r="480" fill="{WHITE}"/>',
    }[shape]
    scale = 1.0 if shape == "square" else LEGACY_SCALE
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">'
        f'{plate}<g transform="translate(512,512) scale({scale}) translate(-512,-512)">{body}</g></svg>'
    )


def render(svg: str, size: int, out: Path) -> None:
    with tempfile.NamedTemporaryFile("w", suffix=".svg", delete=False) as f:
        f.write(svg)
    out.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), "-o", str(out), f.name], check=True)
    os.unlink(f.name)


def main() -> None:
    assets = ios_path() / "meteocool" / "AppIcon.icon" / "Assets"
    if not assets.exists():
        sys.exit(f"{assets} does not exist; pass the iOS checkout as the first argument")

    light = [layer(assets, n) for n in ("cloud", "outline", "rain")]
    dark = [layer(assets, n) for n in ("cloud", "outline-dark", "rain-dark")]
    (RES / "drawable" / "ic_launcher_foreground.xml").write_text(vector(light))
    (RES / "drawable-night").mkdir(exist_ok=True)
    (RES / "drawable-night" / "ic_launcher_foreground.xml").write_text(vector(dark))
    (RES / "drawable" / "ic_launcher_monochrome.xml").write_text(
        vector([layer(assets, n) for n in ("outline", "rain")], monochrome=True)
    )
    (RES / "values" / "ic_launcher_background.xml").write_text(background(WHITE))
    (RES / "values-night").mkdir(exist_ok=True)
    (RES / "values-night" / "ic_launcher_background.xml").write_text(background(NEAR_BLACK))

    for density, size in LEGACY_SIZES.items():
        render(flat_svg(assets, "rounded"), size, RES / f"mipmap-{density}" / "ic_launcher.png")
        render(flat_svg(assets, "circle"), size, RES / f"mipmap-{density}" / "ic_launcher_round.png")
    # Play and F-Droid mask the store icon themselves.
    render(flat_svg(assets, "square"), 512, ROOT / "metadata" / "en-US" / "images" / "icon.png")
    print("wrote the launcher icon, its legacy PNGs and metadata/en-US/images/icon.png")


if __name__ == "__main__":
    main()
